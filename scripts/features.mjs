#!/usr/bin/env node
// Regenerates docs/FEATURES.md from the repository's issues.
//
// Usage:
//   node scripts/features.mjs             write docs/FEATURES.md
//   node scripts/features.mjs --stdout    print instead of writing
//
// Needs the GitHub CLI (`gh`) authenticated for this repository.

import { execFileSync } from 'node:child_process';
import { writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const TYPES = ['feature', 'bug', 'chore'];

function fetchIssues() {
  const out = execFileSync(
    'gh',
    [
      'issue', 'list',
      '--state', 'all',
      '--limit', '5000',
      '--json', 'number,title,labels,state,stateReason,url',
    ],
    { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
  );
  return JSON.parse(out);
}

const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

function status(issue) {
  if (issue.state === 'OPEN') return 'open';
  return issue.stateReason === 'NOT_PLANNED' ? 'not planned' : 'done';
}

function row(issue) {
  const labels = issue.labels.map((l) => l.name);
  const type = TYPES.find((t) => labels.includes(t)) ?? (labels.includes('idea') ? 'idea' : '-');
  const areas = labels
    .filter((l) => l.startsWith('area:'))
    .map((l) => l.slice('area:'.length))
    .sort();
  const title = issue.title.replace(/^TKM-\d+:\s*/, '');
  return `| TKM-${issue.number} | ${cell(title)} | ${type} | ${areas.join(', ') || '-'} | ${status(issue)} | [#${issue.number}](${issue.url}) |`;
}

function render(issues) {
  const sorted = [...issues].sort((a, b) => a.number - b.number);
  return [
    '# Features',
    '',
    'Generated by `node scripts/features.mjs` from the issue tracker. Do not edit by hand.',
    '',
    '| Key | Title | Type | Area | Status | Link |',
    '|---|---|---|---|---|---|',
    ...sorted.map(row),
    '',
  ].join('\n');
}

const text = render(fetchIssues());
if (process.argv.includes('--stdout')) {
  process.stdout.write(text);
} else {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const target = path.join(root, 'docs', 'FEATURES.md');
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, text);
  console.log(`features: wrote ${path.relative(root, target)}`);
}
